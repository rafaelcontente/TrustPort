"""Fairness report generation for bias detection audits."""

import json
from datetime import datetime


def generate_fairness_report(
    metrics: dict[str, float],
    checks: dict[str, bool],
    protected_attribute_name: str = "protected_attribute",
    privileged_group_name: str = "privileged",
    unprivileged_group_name: str = "unprivileged",
    sample_size: int = 0,
    timestamp: str | None = None
) -> str:
    """Generate a human-readable fairness report.
    
    Args:
        metrics: Dictionary of fairness metrics
        checks: Dictionary of threshold checks
        protected_attribute_name: Name of the protected attribute
        privileged_group_name: Name of the privileged group
        unprivileged_group_name: Name of the unprivileged group
        sample_size: Number of samples in the dataset
        timestamp: Timestamp of the analysis (default: current time)
    
    Returns:
        Formatted fairness report (string)
    """
    if timestamp is None:
        timestamp = datetime.now().isoformat()
    
    report = []
    report.append("=" * 80)
    report.append("FAIRNESS & BIAS DETECTION REPORT")
    report.append("=" * 80)
    report.append(f"Timestamp: {timestamp}")
    report.append(f"Sample Size: {sample_size}")
    report.append(f"Protected Attribute: {protected_attribute_name}")
    report.append(f"  - Privileged Group: {privileged_group_name}")
    report.append(f"  - Unprivileged Group: {unprivileged_group_name}")
    report.append("")
    
    report.append("FAIRNESS METRICS:")
    report.append("-" * 80)
    
    # Disparate Impact Ratio
    dir_value = metrics['disparate_impact_ratio']
    dir_status = "✅ PASS" if checks['disparate_impact_ratio_pass'] else "❌ FAIL"
    report.append(f"Disparate Impact Ratio: {dir_value:.4f} {dir_status}")
    report.append("  Threshold: 0.8 - 1.25 (80% rule)")
    if dir_value < 0.8:
        report.append(f"  ⚠️  Adverse impact against {unprivileged_group_name} group")
    elif dir_value > 1.25:
        report.append(f"  ⚠️  Adverse impact against {privileged_group_name} group")
    report.append("")
    
    # Equal Opportunity Difference
    eod_value = metrics['equal_opportunity_difference']
    eod_status = "✅ PASS" if checks['equal_opportunity_difference_pass'] else "❌ FAIL"
    report.append(f"Equal Opportunity Difference: {eod_value:.4f} {eod_status}")
    report.append("  Threshold: ±0.1")
    if eod_value < -0.1:
        report.append(f"  ⚠️  {unprivileged_group_name} group has lower true positive rate")
    elif eod_value > 0.1:
        report.append(f"  ⚠️  {privileged_group_name} group has lower true positive rate")
    report.append("")
    
    # Demographic Parity Difference
    dpd_value = metrics['demographic_parity_difference']
    dpd_status = "✅ PASS" if checks['demographic_parity_difference_pass'] else "❌ FAIL"
    report.append(f"Demographic Parity Difference: {dpd_value:.4f} {dpd_status}")
    report.append("  Threshold: ±0.1")
    if dpd_value < -0.1:
        report.append(f"  ⚠️  {unprivileged_group_name} group has lower positive rate")
    elif dpd_value > 0.1:
        report.append(f"  ⚠️  {privileged_group_name} group has lower positive rate")
    report.append("")
    
    # Overall Assessment
    report.append("OVERALL ASSESSMENT:")
    report.append("-" * 80)
    all_pass = all(checks.values())
    if all_pass:
        report.append("✅ NO BIAS DETECTED - System meets fairness thresholds")
    else:
        report.append("❌ BIAS DETECTED - System requires mitigation")
        failed_metrics = [k.replace('_pass', '') for k, v in checks.items() if not v]
        report.append(f"Failed metrics: {', '.join(failed_metrics)}")
    report.append("")
    
    report.append("RECOMMENDATIONS:")
    report.append("-" * 80)
    if all_pass:
        report.append("• Continue monitoring fairness metrics in production")
        report.append("• Retrain model periodically to prevent drift")
        report.append("• Document fairness assessment for compliance records")
    else:
        report.append("• Investigate root cause of bias (data, model, or labels)")
        report.append("• Consider bias mitigation techniques:")
        report.append("  - Pre-processing: reweight or resample training data")
        report.append("  - In-processing: add fairness constraints to model training")
        report.append("  - Post-processing: adjust decision thresholds per group")
        report.append("• Re-evaluate after mitigation")
    report.append("")
    
    report.append("=" * 80)
    report.append("Report generated by TrustPort Fairness Module")
    report.append("=" * 80)
    
    return "\n".join(report)


def export_fairness_report_json(
    metrics: dict[str, float],
    checks: dict[str, bool],
    protected_attribute_name: str = "protected_attribute",
    sample_size: int = 0,
    timestamp: str | None = None
) -> str:
    """Export fairness report as JSON for programmatic consumption.
    
    Args:
        metrics: Dictionary of fairness metrics
        checks: Dictionary of threshold checks
        protected_attribute_name: Name of the protected attribute
        sample_size: Number of samples in the dataset
        timestamp: Timestamp of the analysis
    
    Returns:
        JSON string of the fairness report
    """
    if timestamp is None:
        timestamp = datetime.now().isoformat()
    
    report = {
        'timestamp': timestamp,
        'sample_size': sample_size,
        'protected_attribute': protected_attribute_name,
        'metrics': metrics,
        'threshold_checks': checks,
        'overall_fair': all(checks.values()),
    }
    
    return json.dumps(report, indent=2)
